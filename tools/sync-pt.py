#!/usr/bin/env python3
"""Keep the two derived parts of the landing page in step with its text.

Run from the repository root after changing index.html or the PT table of assets/i18n.js:

    python3 tools/sync-pt.py

It (1) rewrites the JSON-LD block of index.html (game, publisher, FAQ) from the visible
text and (2) writes pt/index.html, the static Portuguese copy of the landing page, from
index.html and the PT table. Hosting stays a plain folder: nothing here runs on the server.
"""
import json, re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE = "https://bodydefense.com.br"
I18N = (ROOT / "assets/i18n.js").read_text(encoding="utf-8")
HTML = (ROOT / "index.html").read_text(encoding="utf-8")

pt_block = I18N[I18N.index("var PT = {"):I18N.index("};", I18N.index("var PT = {"))]
PT = {}
for m in re.finditer(r'"((?:[^"\\]|\\.)*)"\s*:\s*"((?:[^"\\]|\\.)*)"', pt_block):
	PT[json.loads('"' + m.group(1) + '"')] = json.loads('"' + m.group(2) + '"')


def strip_tags(s):
	return re.sub(r"<[^>]+>", "", s).replace("&amp;", "&").replace("&ecirc;", "ê").strip()


def faq_pairs(html, table=None):
	"""Question and answer text of the FAQ, in English from the HTML or in Portuguese from the table."""
	pairs = []
	for n in range(1, 40):
		q = re.search(r'data-i18n="faq\.q%d">(.*?)</h3>' % n, html)
		a = re.search(r'data-i18n="faq\.a%d">(.*?)</p>' % n, html)
		if not q:
			break
		if table:
			pairs.append((strip_tags(table["faq.q%d" % n]), strip_tags(table["faq.a%d" % n])))
		else:
			pairs.append((strip_tags(q.group(1)), strip_tags(a.group(1))))
	return pairs


def jsonld(desc, url, pairs):
	org = {
		"@type": "Organization", "@id": SITE + "/#apolo", "name": "Apolo Systems",
		"url": SITE + "/apolo/", "logo": SITE + "/assets/apolo/logo.png",
		"email": "contact.apolosystems@gmail.com",
	}
	game = {
		"@type": ["VideoGame", "MobileApplication"], "@id": SITE + "/#game", "name": "Body Defense",
		"url": url, "description": desc, "image": SITE + "/assets/body-defense/og-image.png",
		"applicationCategory": "GameApplication", "operatingSystem": "Android 7.0 or newer",
		"gamePlatform": "Android", "genre": ["Tower defense", "Strategy"], "playMode": "SinglePlayer",
		"inLanguage": ["en", "pt", "fr", "es", "it", "zh", "ja"], "isAccessibleForFree": True,
		"offers": {"@type": "Offer", "price": "0", "priceCurrency": "USD"},
		"audience": {"@type": "PeopleAudience", "suggestedMinAge": 13},
		"author": {"@id": SITE + "/#apolo"}, "publisher": {"@id": SITE + "/#apolo"},
	}
	faq = {
		"@type": "FAQPage", "@id": url + "#faq", "mainEntity": [
			{"@type": "Question", "name": q, "acceptedAnswer": {"@type": "Answer", "text": a}} for q, a in pairs],
	}
	return json.dumps({"@context": "https://schema.org", "@graph": [game, org, faq]}, ensure_ascii=False, indent=1)


def put_jsonld(html, data):
	return re.sub(r'(<script type="application/ld\+json">\n).*?(\n</script>)', lambda m: m.group(1) + data + m.group(2), html, flags=re.S)


# 1. JSON-LD of the English page
desc_en = re.search(r'<meta name="description"[^>]*content="([^"]*)"', HTML).group(1)
en = put_jsonld(HTML, jsonld(desc_en, SITE + "/", faq_pairs(HTML)))
(ROOT / "index.html").write_text(en, encoding="utf-8")

# 2. Portuguese copy
h = en


def sub_inner(h, key, text):
	pat = re.compile(r'(<(\w+)\b[^>]*\bdata-i18n="%s"[^>]*>)(.*?)(</\2>)' % re.escape(key), re.S)
	return pat.sub(lambda m: m.group(1) + text + m.group(4), h)


h = re.sub(r'(<meta name="description" data-i18n="bdp.desc" content=")[^"]*(")', lambda m: m.group(1) + PT["bdp.desc"] + m.group(2), h)
for key in sorted(set(re.findall(r'data-i18n="([^"]+)"', h))):
	if key in PT and key != "bdp.desc":
		h = sub_inner(h, key, PT[key])
# alt texts
h = re.sub(r'alt="[^"]*" data-i18n-alt="([^"]+)"', lambda m: 'alt="%s"' % PT[m.group(1)], h)
h = re.sub(r' data-i18n(-alt)?="[^"]*"', "", h)
# language and metadata
h = h.replace('<html lang="en">', '<html lang="pt-BR">\n<!-- Generated by tools/sync-pt.py from index.html and assets/i18n.js: edit those, not this file. -->', 1)
h = h.replace('<link rel="canonical" href="%s/">' % SITE, '<link rel="canonical" href="%s/pt/">' % SITE)
h = h.replace('content="%s/">' % SITE, 'content="%s/pt/">' % SITE)  # og:url
og_title = "Body Defense: tower defense dentro do corpo humano"
og_desc = "Células de defesa contra vírus, bactérias e fungos. Um tower defense em pixel art para Android com 16 fases. Joga offline, sem precisar de conta."
og_alt = "Body Defense: células de defesa em pixel art diante de vírus em uma veia"
h = h.replace("Body Defense: tower defense inside the human body", og_title)
h = h.replace("Immune cells vs. viruses, bacteria and fungi. A pixel-art tower defense for Android with 16 levels. Plays offline, no account needed.", og_desc)
h = h.replace("Body Defense: pixel-art immune cells facing viruses along a vein", og_alt)
h = h.replace('<meta property="og:locale" content="en_US">\n<meta property="og:locale:alternate" content="pt_BR">',
	'<meta property="og:locale" content="pt_BR">\n<meta property="og:locale:alternate" content="en_US">')
h = put_jsonld(h, jsonld(PT["bdp.desc"], SITE + "/pt/", faq_pairs(en, PT)))
# switcher, footer link, scripts
h = re.sub(r'<span class="lang">.*?</span>', '<span class="lang"><a href="../" hreflang="en" lang="en">EN</a><a href="./" hreflang="pt-BR" lang="pt-BR" aria-current="true">PT</a></span>', h, flags=re.S)
h = h.replace('<a href="pt/" hreflang="pt-BR" lang="pt-BR">Portugu&ecirc;s</a>', '<a href="../" hreflang="en" lang="en">English</a>')
h = re.sub(r'<script src="assets/i18n.js"></script>\n?', "", h)
# relative links: the page sits one folder deeper
h = re.sub(r'<a data-privacy href="([^"]+)"', lambda m: '<a href="../%s#pt"' % m.group(1), h)
def fix(m):
	attr, val = m.group(1), m.group(2)
	if re.match(r"(https?:|mailto:|#|/|\.\./|\./$)", val) or val == "":
		return m.group(0)
	return '%s="../%s"' % (attr, val)
h = re.sub(r'\b(href|src)="([^"]*)"', fix, h)
h = h.replace('href="./"', 'href="./"')
(ROOT / "pt").mkdir(exist_ok=True)
(ROOT / "pt/index.html").write_text(h, encoding="utf-8")
print("ok: index.html JSON-LD and pt/index.html written")
